#!/usr/bin/env python3
"""Stiffness-based contact attribution: rank branches by k, not by force.

Motivation. The existing residual fit (contact_monitor.ContactAttributor) models one
contact with a free force magnitude and ranks candidates by how well their torque
fingerprint explains tau. That ranks by FORCE. The branch that stops the arm is the
one that is STIFF, and in a canopy a soft branch pressed 50 mm can carry more force
than a stiff branch pressed 10 mm -- so force ranking names the wrong branch exactly
when it matters.

Two estimators are implemented and compared here. Both solve for the per-branch
stiffness k_b directly, so the ranking is by stiffness by construction.

  STATIC   tau = sum_b k_b * A_b          A_b = sum_{pairs in b} pen_p * h_p
           Uses the modelled penetration as the spring compression. Costs nothing --
           no extra motion -- and is available at the stall instant.

  PROBE    dtau = sum_b k_b * m_b         m_b = sum_{pairs in b} (-dq . h_p) * h_p
           Displace the arm by dq (e.g. the first waypoints of the retreat, which are
           free), measure the torque change. Does NOT use pen at all, so it is immune
           to penetration error in the model.

h_p = J_p^T r_hat_p is the usual fingerprint (torque per newton, units m), and the
identity that makes the probe estimator cheap is

    d(pen_p) = -(delta x_p) . r_hat_p = -(J_p dq) . r_hat_p = -dq . h_p

so every projection is a joint-space dot product; no workspace displacements needed.

SIGN. This file uses the PHYSICALLY CORRECT convention -- the branch pushes the arm
along +r_hat, so tau_ext = sum f_p J_p^T r_hat_p -- unlike ContactAttributor, which
has the documented sign bug. Truth and estimate are consistent here either way; the
point of stating it is that this file is not blind to the bug the way self_test is.

CONTACT MODEL. f_p = k_b * pen_p, a linear penalty spring, which is the same model
the planner's own vector field uses (force proportional to stiffness x depth). Truth
for the probe estimator is generated by recomputing the geometry at the displaced
pose, so the linearisation is being tested, not assumed.
"""

import argparse
import collections
import glob
import math
import os
import random
import statistics
import sys

import contact_monitor as cm
from contact_monitor import PEN_PROBES, LINK_JOINT_COUNT, ContactAttributor, PandaKin


# ----------------------------------------------------------------------
# small linear algebra (7-vectors, up to 4 unknowns -- no numpy needed)
# ----------------------------------------------------------------------

def dot(a, b):
    return sum(x * y for x, y in zip(a, b))


def solve_lstsq(cols, rhs):
    """Least squares for rhs = sum_i x_i * cols[i]; returns (x, cond) or (None, inf).

    Normal equations with Gauss-Jordan. cond is the 2-norm condition number of the
    Gram matrix estimated from its eigenvalues (n <= 3 here, so this is exact for
    n = 1, 2 and a Jacobi sweep for n = 3).
    """
    n = len(cols)
    G = [[dot(cols[i], cols[j]) for j in range(n)] for i in range(n)]
    b = [dot(cols[i], rhs) for i in range(n)]
    cond = gram_cond(G)
    A = [row[:] + [b[i]] for i, row in enumerate(G)]
    for c in range(n):
        p = max(range(c, n), key=lambda r: abs(A[r][c]))
        if abs(A[p][c]) < 1e-18:
            return None, float("inf")
        A[c], A[p] = A[p], A[c]
        pv = A[c][c]
        A[c] = [v / pv for v in A[c]]
        for r in range(n):
            if r == c:
                continue
            f = A[r][c]
            if f:
                A[r] = [vr - f * vc for vr, vc in zip(A[r], A[c])]
    return [A[i][n] for i in range(n)], cond


def gram_cond(G):
    """sqrt(lambda_max/lambda_min) of a small symmetric PD matrix, via Jacobi."""
    n = len(G)
    A = [row[:] for row in G]
    for _ in range(60):
        off = [(abs(A[i][j]), i, j) for i in range(n) for j in range(i + 1, n)]
        if not off:
            break
        m, i, j = max(off)
        if m < 1e-15 * max(abs(A[k][k]) for k in range(n)):
            break
        if abs(A[i][i] - A[j][j]) < 1e-30:
            th = math.pi / 4
        else:
            th = 0.5 * math.atan2(2 * A[i][j], A[i][i] - A[j][j])
        c, s = math.cos(th), math.sin(th)
        for k in range(n):
            aik, ajk = A[i][k], A[j][k]
            A[i][k], A[j][k] = c * aik + s * ajk, -s * aik + c * ajk
        for k in range(n):
            aki, akj = A[k][i], A[k][j]
            A[k][i], A[k][j] = c * aki + s * akj, -s * aki + c * akj
    ev = [A[k][k] for k in range(n)]
    lo, hi = min(ev), max(ev)
    return math.sqrt(hi / lo) if lo > 1e-18 else float("inf")


# ----------------------------------------------------------------------
# contacts and fingerprints
# ----------------------------------------------------------------------

def contacts_at(kin, att, q):
    """Every real (probe, soft cylinder) penetration at q, with its fingerprint."""
    out = []
    pos = kin.probe_positions(q)
    J = kin.probe_jacobians(q)
    for pi, (pname, _off, prad) in enumerate(PEN_PROBES):
        for ci, cyl in enumerate(att.cyls):
            if not cyl["soft"]:
                continue
            seg = [cyl["p1"][d] - cyl["p0"][d] for d in range(3)]
            sq = sum(v * v for v in seg)
            if sq < 1e-12:
                continue
            u = max(0.0, min(1.0, sum((pos[pi][d] - cyl["p0"][d]) * seg[d]
                                      for d in range(3)) / sq))
            ax = cm._lerp(cyl["p0"], cyl["p1"], u)
            rad = [pos[pi][d] - ax[d] for d in range(3)]
            rn = math.sqrt(sum(v * v for v in rad))
            if rn < 1e-6:
                continue
            pen = (cyl["r"] + prad) - rn
            if pen <= 0.0:
                continue
            rhat = [v / rn for v in rad]
            k_joint = LINK_JOINT_COUNT[pname]
            # h = J^T r_hat, zeroed on joints distal to the contact
            h = [(sum(J[pi][d][j] * rhat[d] for d in range(3)) if j < k_joint else 0.0)
                 for j in range(7)]
            out.append({"pen": pen, "probe": pi, "cyl": ci, "u": u,
                        "rhat": rhat, "link": pname, "h": h})
    out.sort(key=lambda c: -c["pen"])
    return out


def branches_of(contacts):
    """Group contacts by cylinder index, deepest branch first."""
    by = collections.defaultdict(list)
    for c in contacts:
        by[c["cyl"]].append(c)
    order = sorted(by, key=lambda b: -max(c["pen"] for c in by[b]))
    return order, by


# ----------------------------------------------------------------------
# forward model (truth)
# ----------------------------------------------------------------------

def tau_of(contacts, kstiff):
    """tau = sum_p k_{branch(p)} * pen_p * h_p   (linear penalty spring)."""
    tau = [0.0] * 7
    for c in contacts:
        f = kstiff[c["cyl"]] * c["pen"]
        for j in range(7):
            tau[j] += f * c["h"][j]
    return tau


# ----------------------------------------------------------------------
# estimators
# ----------------------------------------------------------------------

def est_static(order, by, tau):
    """tau = sum_b k_b A_b,  A_b = sum_{p in b} pen_p h_p."""
    cols = []
    for b in order:
        A = [0.0] * 7
        for c in by[b]:
            for j in range(7):
                A[j] += c["pen"] * c["h"][j]
        cols.append(A)
    return solve_lstsq(cols, tau)


def est_rate(order, by, slope, qdot):
    """dtau/dt = sum_b k_b m_b ,  m_b = sum_{p in b} (-qdot . h_p) h_p.

    The continuous form of est_probe: the displacement comes from the motion the arm
    is ALREADY making on its approach, so there is no probe to pay for. df/dt = k*v,
    and v = -qdot . h is the penetration rate, computed from the encoders.

    Why this beats ranking by tau (the old method): tau ranks by k*x, and x is biased
    systematically against the rigid branch -- it is rigid, so by definition it has
    barely moved. dtau/dt ranks by k*v, and v carries no such bias.

    The catch: at a stall v -> 0, so this signal exists only DURING the approach. The
    window has to be taken before the arm stops, not after.
    """
    cols = []
    for b in order:
        m = [0.0] * 7
        for c in by[b]:
            rate = -dot(qdot, c["h"])          # d(pen_p)/dt
            for j in range(7):
                m[j] += rate * c["h"][j]
        cols.append(m)
    return solve_lstsq(cols, slope)


def est_rate_raw(order, by, slope):
    """Rank by the RAW force-change rate -- no division by the penetration rate.

    This is the OLD method's machinery with dtau/dt substituted for tau: fit the
    measured rate with each branch's aggregate fingerprint and rank by the magnitude
    of the fitted coefficient. The coefficient is c_b = k_b * v_b (N/s), so this ranks
    by k*v rather than by k.

    Worth testing separately because it is the simplest reading of "whichever branch's
    force rises fastest is the rigid one" -- it needs no penetration rate at all. It is
    exact only when v is similar across branches; where the probe direction is nearly
    tangential to one branch, that branch's v is small and it will be under-ranked.
    """
    cols = []
    for b in order:
        A = [0.0] * 7
        for c in by[b]:
            for j in range(7):
                A[j] += c["h"][j]
        cols.append(A)
    return solve_lstsq(cols, slope)


def fit_slopes(ts, taus):
    """Per-joint least-squares slope of tau against t.

    A regression over the whole window rather than a two-point difference: with N
    samples the slope's standard error falls as sigma/(sigma_t*sqrt(N)), which at
    240 Hz over 0.5 s is ~13x better than differencing the endpoints.
    """
    n = len(ts)
    tbar = sum(ts) / n
    stt = sum((t - tbar) ** 2 for t in ts)
    if stt < 1e-18:
        return None
    out = []
    for j in range(7):
        ybar = sum(v[j] for v in taus) / n
        out.append(sum((t - tbar) * (v[j] - ybar) for t, v in zip(ts, taus)) / stt)
    return out


def est_probe(order, by, dtau, dq):
    """dtau = sum_b k_b m_b,  m_b = sum_{p in b} (-dq . h_p) h_p.

    Note pen never appears: this estimator is immune to penetration error in the
    model (it still needs r_hat, hence the axis direction).
    """
    cols = []
    for b in order:
        m = [0.0] * 7
        for c in by[b]:
            proj = -dot(dq, c["h"])          # = d(pen_p) for unit dq
            for j in range(7):
                m[j] += proj * c["h"][j]
        cols.append(m)
    return solve_lstsq(cols, dtau)


# ----------------------------------------------------------------------
# case discovery
# ----------------------------------------------------------------------

def find_cases(kin, att, results_dir, want_branches, max_cases, stride):
    """Poses with exactly `want_branches` distinct branches in contact.

    Needs a predecessor waypoint to supply a retreat direction, so waypoint 0 is
    skipped. Takes at most one case per path to keep the cases independent.
    """
    cases = []
    for p in sorted(glob.glob(os.path.join(results_dir, "grasp_path_*.csv"))):
        with open(p) as f:
            wps = [[float(x) for x in ln.split(",")] for ln in f if ln.strip()]
        picked = None
        for i in range(1, len(wps), stride):
            cs = contacts_at(kin, att, wps[i])
            order, _ = branches_of(cs)
            if len(order) != want_branches:
                continue
            # prefer the deepest such pose on this path
            depth = max(c["pen"] for c in cs)
            if picked is None or depth > picked[0]:
                picked = (depth, i, wps[i], wps[i - 1])
        if picked:
            cases.append({"path": os.path.basename(p), "wp": picked[1],
                          "q": picked[2], "q_prev": picked[3]})
        if len(cases) >= max_cases:
            break
    return cases


# ----------------------------------------------------------------------
# one trial
# ----------------------------------------------------------------------

def shift_model(att, nominal, vec):
    for idx, c in enumerate(att.cyls):
        c["p0"] = [nominal[idx]["p0"][d] + vec[d] for d in range(3)]
        c["p1"] = [nominal[idx]["p1"][d] + vec[d] for d in range(3)]


def trial(kin, att, case, stiff_ratio, probe_mm, noise_nm, rng, rigid_choice,
          model_offset_cm=0.0, nominal=None, avg_n=1,
          win_mm=5.0, win_s=0.5, win_n=120):
    """Returns per-estimator results, or None if the case is unusable.

    model_offset_cm > 0: TRUTH is generated against the nominal model (the real tree
    is where the planned path thought it was), then every cylinder is displaced by one
    random rigid vector and BOTH estimators work from that wrong model. This is the
    comparison that matters, because est_static divides by the modelled penetration
    while est_probe never uses it.
    """
    cs = contacts_at(kin, att, case["q"])
    order, by = branches_of(cs)
    if len(order) < 1:
        return None
    # assign stiffnesses: everything soft at k0, one branch stiffened
    k0 = 300.0                              # N/m, a plausible thin-branch value
    rigid = order[-1] if rigid_choice == "shallowest" else order[0]
    ks = {b: k0 for b in order}
    ks[rigid] = k0 * stiff_ratio

    tau = tau_of(cs, ks)

    # --- probe displacement: toward the previous waypoint (the retreat), scaled so
    #     the deepest contact's probe moves about probe_mm
    dq_dir = [a - b for a, b in zip(case["q_prev"], case["q"])]
    nrm = math.sqrt(dot(dq_dir, dq_dir))
    if nrm < 1e-9:
        return None
    deepest = cs[0]
    rate = abs(dot([v / nrm for v in dq_dir], deepest["h"]))   # m of pen per rad
    if rate < 1e-6:
        return None
    scale = (probe_mm * 1e-3) / rate
    dq = [v / nrm * scale for v in dq_dir]
    q2 = [a + b for a, b in zip(case["q"], dq)]

    # --- truth at the displaced pose, recomputed NONLINEARLY
    cs2 = contacts_at(kin, att, q2)
    ks2 = collections.defaultdict(lambda: k0)
    ks2.update(ks)
    tau2 = tau_of(cs2, ks2)

    def noisy(v):
        """Average avg_n independent readings -- what the real 1 kHz stream gives you.

        Effective sigma is noise_nm/sqrt(avg_n). This matters asymmetrically: the
        static estimator reads a large tau and is already SNR-rich, while the probe
        reads a small dtau and is SNR-starved, so averaging helps the probe far more.
        With a single sample the comparison is biased against the probe.
        """
        if noise_nm <= 0:
            return list(v)
        s_eff = noise_nm / math.sqrt(max(1, avg_n))
        return [x + rng.gauss(0.0, s_eff) for x in v]

    tau_m, tau2_m = noisy(tau), noisy(tau2)
    dtau_m = [a - b for a, b in zip(tau2_m, tau_m)]

    out = {"rigid": rigid, "order": order, "nb": len(order),
           "k_true": ks[rigid], "k0": k0}

    # ---- what the ESTIMATOR believes the geometry is ----
    e_order, e_by = order, by
    if model_offset_cm > 0.0 and nominal is not None:
        v = [rng.gauss(0, 1) for _ in range(3)]
        n = math.sqrt(sum(x * x for x in v)) or 1.0
        vec = [x / n * model_offset_cm * 0.01 for x in v]
        shift_model(att, nominal, vec)
        try:
            e_cs = contacts_at(kin, att, case["q"])
            e_order, e_by = branches_of(e_cs)
        finally:
            shift_model(att, nominal, [0.0, 0.0, 0.0])
        if rigid not in e_order:
            # the wrong model no longer believes the rigid branch is touched at all
            out["static"] = {"ok": False, "cond": float("nan"),
                             "k_rigid": float("nan"), "relerr": float("nan")}
            out["probe"] = dict(out["static"])
            fmax0 = {b: max(ks[b] * c["pen"] for c in by[b]) for b in order}
            out["force_rank_ok"] = max(fmax0, key=lambda b: fmax0[b]) == rigid
            return out

    # ---- RATE: regress tau over the final approach INTO this pose ----
    # The window ends at the case pose and approaches it along the path direction,
    # scaled so the deepest contact's penetration changes by win_mm -- the same
    # amount the discrete probe uses, but spread over win_n samples.
    rate_res = (None, float("inf"))
    rate_raw_res = (None, float("inf"))
    qdot = [0.0] * 7
    if win_n >= 8:
        step = [v / win_s for v in dq]                 # qdot, rad/s
        qdot = step
        ts, taus = [], []
        for i in range(win_n):
            frac = (i + 1) / win_n                     # ends AT the case pose
            qi = [a - b * (1.0 - frac) for a, b in zip(case["q"], dq)]
            ci = contacts_at(kin, att, qi)
            ks_i = collections.defaultdict(lambda: k0)
            ks_i.update(ks)
            tv = tau_of(ci, ks_i)
            if noise_nm > 0:
                tv = [x + rng.gauss(0.0, noise_nm) for x in tv]
            ts.append(frac * win_s)
            taus.append(tv)
        sl = fit_slopes(ts, taus)
        if sl is not None:
            rate_res = est_rate(e_order, e_by, sl, qdot)
            rate_raw_res = est_rate_raw(e_order, e_by, sl)

    for name, (kest, cond) in (
            ("static", est_static(e_order, e_by, tau_m)),
            ("probe",  est_probe(e_order, e_by, dtau_m, dq)),
            ("rate",   rate_res),
            ("rate_raw", rate_raw_res)):
        if kest is None:
            out[name] = None
            continue
        ki = {b: kest[i] for i, b in enumerate(e_order)}
        pick = max(ki, key=lambda b: ki[b])
        out[name] = {
            "ok": pick == rigid,
            "cond": cond,
            "k_rigid": ki[rigid],
            # rate_raw's coefficient is k*v (N/s), not a stiffness -- ranking only
            "relerr": (float("nan") if name == "rate_raw"
                       else abs(ki[rigid] - ks[rigid]) / ks[rigid]),
        }
    # the OLD behaviour for reference: rank by force (deepest x k) -> which branch
    # carries the most force
    fmax = {b: max(ks[b] * c["pen"] for c in by[b]) for b in order}
    out["force_rank_ok"] = max(fmax, key=lambda b: fmax[b]) == rigid
    return out


# ----------------------------------------------------------------------

def run(kin, att, cases, label, stiff_ratio, probe_mm, noise_levels, seeds,
        rigid_choice, model_offset_cm=0.0, nominal=None, avg_n=1,
        win_mm=5.0, win_s=0.5, win_n=120):
    print(f"\n{'='*86}")
    print(f"{label}   stiffness ratio {stiff_ratio:.0f}x on the {rigid_choice} branch, "
          f"probe {probe_mm:.1f} mm, model offset {model_offset_cm:.1f} cm, "
          f"avg {avg_n} sample(s)")
    print(f"{'='*86}")
    if not cases:
        print("  no cases found")
        return
    print(f"  cases: {len(cases)}  "
          f"({', '.join(c['path'].replace('grasp_path_','').replace('.csv','')+'@wp'+str(c['wp']) for c in cases[:6])}"
          f"{' ...' if len(cases)>6 else ''})")
    for nm in noise_levels:
        acc = {"static": [], "probe": [], "rate": [], "rate_raw": []}
        errs = {"static": [], "probe": [], "rate": [], "rate_raw": []}
        conds = {"static": [], "probe": [], "rate": [], "rate_raw": []}
        force_ok = []
        for case in cases:
            for s in seeds:
                r = trial(kin, att, case, stiff_ratio, probe_mm, nm,
                          random.Random(s), rigid_choice,
                          model_offset_cm, nominal, avg_n,
                          win_mm, win_s, win_n)
                if r is None:
                    continue
                force_ok.append(r["force_rank_ok"])
                for nameq in ("static", "probe", "rate", "rate_raw"):
                    if r[nameq] is None:
                        acc[nameq].append(False)
                        continue
                    acc[nameq].append(r[nameq]["ok"])
                    errs[nameq].append(r[nameq]["relerr"])
                    conds[nameq].append(r[nameq]["cond"])
        n = len(acc["probe"])
        if n == 0:
            print(f"  noise {nm:4.2f} : no usable trials")
            continue
        def pc(key):
            a = sum(1 for v in acc[key] if v)
            e = statistics.median(errs[key]) * 100 if errs[key] else float('nan')
            c = statistics.median(conds[key]) if conds[key] else float('nan')
            return f"{a:3d}/{n:<3d} ({100*a/n:5.1f}%)  k err {e:6.1f}%  cond {c:6.1f}"
        fo = sum(1 for v in force_ok if v)
        print(f"  noise {nm:4.2f} N*m | STATIC {pc('static')}")
        print(f"{'':19s}| PROBE  {pc('probe')}")
        print(f"{'':19s}| RATE   {pc('rate')}")
        print(f"{'':19s}| RAW-dF {pc('rate_raw')}")
        print(f"{'':19s}| force-ranking (old behaviour) would pick the rigid branch "
              f"{fo}/{len(force_ok)} ({100*fo/max(1,len(force_ok)):.0f}%)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", required=True)
    ap.add_argument("--cases", type=int, default=6)
    ap.add_argument("--seeds", type=int, default=5)
    ap.add_argument("--stride", type=int, default=3)
    ap.add_argument("--ratio", type=float, default=5.0)
    ap.add_argument("--probe-mm", type=float, default=2.0)
    ap.add_argument("--rigid", default="shallowest",
                    choices=["shallowest", "deepest"])
    ap.add_argument("--model-offset-cm", type=float, default=0.0)
    ap.add_argument("--win-mm", type=float, default=5.0)
    ap.add_argument("--win-s", type=float, default=0.5)
    ap.add_argument("--win-n", type=int, default=120)
    ap.add_argument("--avg-samples", type=int, default=1,
                    help="readings averaged per torque measurement; the real stream "
                         "gives ~500 over a 0.5 s probe at 1 kHz")
    args = ap.parse_args()

    kin = PandaKin()
    att = ContactAttributor(os.path.join(args.results, "scene_layout.json"), kin)
    print(f"scene {args.results}")
    print(f"  cylinders {len(att.cyls)}  soft {sum(1 for c in att.cyls if c['soft'])}")
    seeds = list(range(args.seeds))
    noise = [0.0, 0.1, 0.5, 1.0]
    nominal = [{"p0": list(c["p0"]), "p1": list(c["p1"])} for c in att.cyls]

    for nb in (1, 2, 3):
        cases = find_cases(kin, att, args.results, nb, args.cases, args.stride)
        run(kin, att, cases, f"{nb} BRANCH{'ES' if nb > 1 else ''} IN CONTACT",
            args.ratio, args.probe_mm, noise, seeds, args.rigid,
            args.model_offset_cm, nominal, args.avg_samples,
            args.win_mm, args.win_s, args.win_n)
    return 0


if __name__ == "__main__":
    sys.exit(main())
